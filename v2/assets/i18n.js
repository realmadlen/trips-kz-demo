  var LANGS = ['ru', 'kk', 'en'];
  var HTML_LANG = { ru: 'ru', kk: 'kk', en: 'en' };
  var current = 'ru';

  function t(key, vars) {
    var table = DICT[current] || DICT.ru;
    var s = table[key];
    if (s === undefined) s = DICT.ru[key];
    if (s === undefined) return key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, function (m, name) {
        return vars[name] === undefined ? m : vars[name];
      });
    }
    return s;
  }

  /* Полнота словаря проверяется в браузере, а не на глаз: недостающие ключи
     печатаются в консоль при загрузке. */
  function audit() {
    var base = Object.keys(DICT.ru), missing = [];
    LANGS.forEach(function (l) {
      base.forEach(function (k) { if (DICT[l][k] === undefined) missing.push(l + ':' + k); });
    });
    if (missing.length) console.warn('[i18n] нет перевода:', missing);
    return missing;
  }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':');
        if (p.length === 2) el.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
  }

  function set(lang) {
    if (LANGS.indexOf(lang) === -1) lang = 'ru';
    current = lang;
    document.documentElement.lang = HTML_LANG[lang];
    try { localStorage.setItem('trips.lang', lang); } catch (e) {}
    apply(document);
    document.dispatchEvent(new CustomEvent('lang:change', { detail: { lang: lang } }));
  }

  function stored() {
    try { return localStorage.getItem('trips.lang'); } catch (e) { return null; }
  }

  return {
    langs: LANGS,
    t: t,
    apply: apply,
    set: set,
    audit: audit,
    get current() { return current; },
    init: function () {
      var url = new URLSearchParams(location.search).get('lang');
      set(url || stored() || 'ru');
      audit();
    },
    name: function (obj) {
      if (!obj) return '';
      return obj[current] || obj.ru || '';
    }
  };
